import static eu.glazelab.api.service.GlazeService.UNKNOWN_GLAZE;

@RestController @RequestMapping("/api")
@RequiredArgsConstructor
public class CatalogController {
    public static final String UNKNOWN_BARCODE = "Unknown barcode";
    /** How many corrections the change log answers at most, newest first. */
    public static final int HISTORY_LIMIT = 100;

    /**
     * {@code jarSizeG} is optional: absent or null keeps the entry's jar size (a new entry starts without one).
     * {@code quantityG} absent or null keeps the stored amount (a size-only save; a new entry starts at 0 g); one of the
     * two is required.
     */
    public record StockInput(@NotNull UUID glazeId,
                      @Schema(nullable = true) @Min(0) @Max(value = StockService.MAX_QUANTITY_G, message = StockService.AMOUNT_TOO_LARGE) Integer quantityG,
                      @Schema(nullable = true) @Min(1) @Max(100_000) Integer jarSizeG,
                      @NotBlank @Schema(allowableValues = {"personal", "club"}) String ownerType, @Schema(nullable = true) UUID clubId) {}
    /**
     * {@code POST /api/stock/add}: {@code addG} grams more for the owner's entry (created when missing). {@code jarSizeG}
     * is stored only on an entry without a jar size (a new one included); {@code replaceJarSize} true replaces a stored
     * size on purpose (see {@link StockService#add}). {@code requestId} (optional, generated by the client per addition
     * and sent again when it repeats one whose answer was lost) makes a repeat answer the entry without adding again.
     */
    public record StockAddition(@NotNull UUID glazeId, @NotNull @Min(1) @Max(StockService.MAX_QUANTITY_G) Integer addG,
                      @Schema(nullable = true) @Min(1) @Max(100_000) Integer jarSizeG,
                      @NotBlank @Schema(allowableValues = {"personal", "club"}) String ownerType, @Schema(nullable = true) UUID clubId,
                      @Schema(nullable = true) Boolean replaceJarSize, @Schema(nullable = true) UUID requestId) {}
    /** Barcodes to remove, then to add, as typed: the server normalizes them (see model.Barcodes). */
    public record BarcodeEdit(@Schema(nullable = true) @Size(max = 10) List<@NotNull @Size(max = 32) String> add,
            @Schema(nullable = true) @Size(max = 10) List<@NotNull @Size(max = 32) String> remove) {
        List<String> adding() { return add == null ? List.of() : add; }
        List<String> removing() { return remove == null ? List.of() : remove; }
    }

    private final GlazeRepository glazes;
    private final GlazeEditRepository edits;
    private final StockRepository stocks;
    private final ImageRecordRepository images;
    private final CurrentUser current;
    private final GlazeService glazeService;
    private final StockService stockService;
    private final StockAdditionRepeats repeats;
    private final LibraryViews views;
    private final ChangeRecorder changes;

    @GetMapping("/glazes") @Transactional(readOnly = true) List<GlazeView> glazes(Authentication auth) {
        return views.glazes(current.viewer(auth));
    }

    /**
     * The glaze whose packaging carries a barcode (normalized like model.Barcodes), with the pictures the
     * caller may see. 400 for a value that is no valid barcode, 404 when no glaze has it.
     */
    @GetMapping("/barcodes/{barcode}") @Transactional(readOnly = true)
    GlazeView glazeByBarcode(@PathVariable String barcode, Authentication auth) {
        UUID glazeId = glazes.findIdByBarcode(Barcodes.valid(barcode))
                .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, UNKNOWN_BARCODE));
        Glaze glaze = glazes.findById(glazeId).orElseThrow();
        return GlazeView.of(glaze, ImageView.visibleViews(images.findByGlaze_IdOrderByCreatedAtDesc(glazeId), current.viewer(auth)),
                GlazeEditRepository.byGlaze(edits.latestOf(glazeId)).get(glazeId));
    }

    /**
     * Any signed-in user corrects a glaze's name and notes, wiki-style; the code only a site admin or while no
     * combination uses the glaze (403 otherwise), a code the manufacturer already has is 409. Each changed field
     * joins the public change log. Answers the glaze with the pictures the caller may see.
     */
    @PatchMapping("/glazes/{id}") GlazeView correctGlaze(@PathVariable UUID id, @Valid @RequestBody GlazeCorrection body,
            Authentication auth) {
        UUID actor = current.user(auth).getId();
        return glazeService.correct(id, body, actor, current.viewer(auth));
    }

    /**
     * The public change log of a glaze, newest first, for everyone who can see the glaze (all glazes are public,
     * so guests too): at most {@link #HISTORY_LIMIT} corrections, {@code more} when older ones exist. Editors
     * appear by display name only (null once the account was deleted).
     */
    @GetMapping("/glazes/{id}/history") @Transactional(readOnly = true) GlazeHistoryView glazeHistory(@PathVariable UUID id) {
        if (!glazes.existsById(id)) throw new ResponseStatusException(HttpStatus.NOT_FOUND, UNKNOWN_GLAZE);
        var page = PageRequest.of(0, HISTORY_LIMIT + 1, Sort.by(Sort.Order.desc("editedAt"), Sort.Order.asc("field")));
        var entries = edits.history(id, page);
        return new GlazeHistoryView(entries.stream().limit(HISTORY_LIMIT).map(GlazeEditRepository.Entry::view).toList(),
                entries.size() > HISTORY_LIMIT);
    }
    /**
     * Any signed-in user may add a glaze, with an existing manufacturer or a new one, and optionally put it
     * on a shelf in the same transaction ({@code stock}: the rules and lock order of {@code POST /api/stock}).
     * Answers with the stored glaze and stock entry so clients need not reload their listings.
     */
    @PostMapping("/glazes") GlazeCreatedView addGlaze(@Valid @RequestBody NewGlaze body, Authentication auth) {
        return glazeService.add(body, current.user(auth));
    }

    /** Any signed-in user may tag any glaze; removals apply before additions. */
    @PatchMapping("/glazes/{id}/tags") @Transactional TagsView editGlazeTags(
            @PathVariable UUID id, @Valid @RequestBody TagEdit body, Authentication auth) {
        current.user(auth);
        // Locked, so concurrent edits of one glaze apply in turn and the tag limit holds.
        Glaze glaze = glazes.lockById(id).orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, UNKNOWN_GLAZE));
        var tags = Tags.edited(glaze.getTags(), body.adding(), body.removing());
        if (!tags.equals(glaze.getTags())) changes.glaze(id);
        glaze.setTags(tags);
        return TagsView.of(glaze.getTags());
    }

    /**
     * Any signed-in user may add or remove barcodes of any glaze, like tags; removals apply before additions.
     * A barcode of another glaze is refused with 409 (it must be removed there first).
     */
    @PatchMapping("/glazes/{id}/barcodes") BarcodesView editGlazeBarcodes(
            @PathVariable UUID id, @Valid @RequestBody BarcodeEdit body, Authentication auth) {
        current.user(auth);
        return glazeService.editBarcodes(id, body.adding(), body.removing());
    }

    /**
     * Site admins remove a glaze completely: its stock rows, favorites, tags, pictures (records and stored
     * objects) and its manufacturer when this was the manufacturer's last glaze, so that name and short ID
     * become free again (the picker only knows manufacturers through the glaze listing). Refused with 409
     * while combination steps use the glaze. Stored objects are deleted only after the commit, so a rollback
     * never leaves records pointing at deleted files; a failed delete leaves an unreferenced file, logged.
     */
    @DeleteMapping("/glazes/{id}") @ResponseStatus(HttpStatus.NO_CONTENT)
    @ApiResponse(responseCode = "409", description = "Combination steps use the glaze",
            content = @Content(schema = @Schema(implementation = GlazeInUseView.class)))
    void removeGlaze(@PathVariable UUID id, Authentication auth) {
        glazeService.remove(id, current.siteAdmin(auth).getId());
    }

    @GetMapping("/stock") @Transactional(readOnly = true) List<StockView> stock(Authentication auth) {
        current.user(auth);
        var viewer = current.viewer(auth);
        List<Stock> visible = new ArrayList<>(stocks.findByUser_Id(viewer.userId()));
        if (!viewer.clubIds().isEmpty()) visible.addAll(stocks.findByClub_IdIn(List.copyOf(viewer.clubIds())));
        return visible.stream().sorted(Comparator.comparing((Stock s) -> s.getGlaze().getManufacturer().getName())
                        .thenComparing(s -> s.getGlaze().getName()))
                .map(s -> StockView.of(s, viewer.userId(), viewer.adminClubIds())).toList();
    }
    /**
     * Sets the amount (last write wins: "Used up", a typed amount) and/or the jar size; a jar added to what is stored is
     * {@code POST /api/stock/add}. 400 when neither is sent.
     */
    @PostMapping("/stock") @Transactional IdView saveStock(
            @Valid @RequestBody StockInput body, Authentication auth) {
        AppUser actor = current.user(auth);
        if (body.quantityG() == null && body.jarSizeG() == null)
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, StockService.NOTHING_TO_SAVE);
        Glaze glaze = glazes.findById(body.glazeId())
                .orElseThrow(() -> new ResponseStatusException(HttpStatus.BAD_REQUEST, UNKNOWN_GLAZE));
        // Lock the owner so concurrent first saves update one row instead of racing on its unique index.
        StockService.Owner owner = stockService.lockOwner(actor, stockService.ownerOf(body.ownerType(), body.clubId()));
        Stock stock = stockService.save(owner, glaze, body.quantityG(), body.jarSizeG());
        return new IdView(stock.getId());
    }

    /**
     * "+1 jar" and the one-click add: adds the grams to the amount stored now (see {@link StockService#add}), so a device
     * whose shelf is stale never loses another device's or member's jar. Answers the entry as the caller sees it, so the
     * client shows the server's total. A {@code requestId} the account sent with an earlier addition of this glaze in the
     * last minutes answers that entry as it is now and adds nothing ({@link StockAdditionRepeats}); checked under the owner
     * lock, so a repeat waiting behind the first sees it.
     */
    @PostMapping("/stock/add") @Transactional StockView addStock(@Valid @RequestBody StockAddition body, Authentication auth) {
        AppUser actor = current.user(auth);
        Glaze glaze = glazes.findById(body.glazeId())
                .orElseThrow(() -> new ResponseStatusException(HttpStatus.BAD_REQUEST, UNKNOWN_GLAZE));
        StockService.Owner owner = stockService.lockOwner(actor, stockService.ownerOf(body.ownerType(), body.clubId()));
        UUID request = body.requestId();
        // An entry removed since is added again, like any "+1 jar" on a row another device removed.
        Stock stock = request == null ? null
                : repeats.earlier(actor.getId(), request, glaze.getId()).flatMap(stocks::findById)
                        .filter(found -> found.getClub() == null ? owner.club() == null
                                : owner.club() != null && found.getClub().getId().equals(owner.club().getId()))
                        .orElse(null);
        if (stock == null) {
            stock = stockService.add(owner, glaze, body.addG(), body.jarSizeG(), Boolean.TRUE.equals(body.replaceJarSize()));
            if (request != null) repeats.remember(actor.getId(), request, glaze.getId(), stock.getId());
        }
        return StockView.of(stock, actor.getId(), current.viewer(auth).adminClubIds());
    }

    /** The owner keeps a personal entry from their buddies, or shows it again (see {@link StockService#keepPrivate}). */
    @PatchMapping("/stock/{id}") @Transactional @ResponseStatus(HttpStatus.NO_CONTENT)
    void editStockPrivacy(@PathVariable UUID id, @Valid @RequestBody StockPrivacy body, Authentication auth) {
        stockService.keepPrivate(current.user(auth), id, body.keepPrivate());
    }

    /** Removes a stock entry by {@code Stock.removableBy}: 403 for a member without the right, 404 for everyone else (see {@link StockService#remove}). */
    @DeleteMapping("/stock/{id}") @Transactional @ResponseStatus(HttpStatus.NO_CONTENT)
    void removeStock(@PathVariable UUID id, Authentication auth) {
        stockService.remove(current.user(auth), id);
    }
}
