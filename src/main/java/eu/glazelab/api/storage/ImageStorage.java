package eu.glazelab.api.storage;

import java.io.IOException;

/**
 * Stores encoded images under opaque keys. {@link #get} throws {@link java.nio.file.NoSuchFileException}
 * when the key has no stored image, whichever adapter is configured. Every picture has two objects: the full
 * size under its record's key ({@code <uuid>.jpg}) and the card size under {@link #cardKey} of that key.
 */
public interface ImageStorage {
    void put(String key, byte[] jpeg) throws IOException;
    byte[] get(String key) throws IOException;
    void delete(String key) throws IOException;

    /** Keys are generated by the API (a UUID plus extension); anything else is rejected before storage access. */
    static String checkKey(String key) {
        if (key == null || !key.matches("[a-f0-9-]{36}(\\.card)?\\.jpg")) throw new IllegalArgumentException("Invalid storage key");
        return key;
    }

    /** The card-size object of the picture stored under {@code key}: {@code <uuid>.card.jpg} beside {@code <uuid>.jpg}. */
    static String cardKey(String key) {
        if (key == null || !key.matches("[a-f0-9-]{36}\\.jpg")) throw new IllegalArgumentException("Invalid storage key");
        return key.substring(0, key.length() - ".jpg".length()) + ".card.jpg";
    }
}
